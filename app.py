# --- Page Configuration ---
st.set_page_config(page_title="AI Master Tutor", page_icon="🤖", layout="wide", initial_sidebar_state="expanded")

# --- Session State Initialization ---
if "current_session_id" not in st.session_state:
    st.session_state.current_session_id = None
if "stage" not in st.session_state:
    st.session_state.stage = "topic_selection"
if "chat_history" not in st.session_state:
    st.session_state.chat_history = []
if "topic" not in st.session_state:
    st.session_state.topic = ""
if "theme" not in st.session_state:
    st.session_state.theme = "Dark 🌙" 

# ଡାଉନଲୋଡ୍ ଫାଇଲ୍ ଗୁଡିକୁ ମନେ ରଖିବା ପାଇଁ
if "main_notes" not in st.session_state:
    st.session_state.main_notes = None
if "quiz_book" not in st.session_state:
    st.session_state.quiz_book = None

# --- Text/Markdown File Generation ---
def create_file(title, text_content):
    content = f"# {title}\n\n{text_content}\n\n---\n*Generated by AI Master Tutor*"
    return content.encode('utf-8')

